import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const runtime = process.env.CODEX_BROWSER_MODULE || 'C:/Users/34711/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright';
const { chromium } = require(runtime);
await mkdir('artifacts/browser', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1512, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
const failedRequests = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('requestfailed', request => { if (!request.failure()?.errorText.includes('ERR_ABORTED')) failedRequests.push({ url: request.url(), failure: request.failure() }); });
await page.goto('http://127.0.0.1:8765', { waitUntil: 'domcontentloaded' });
await page.getByRole('heading', { name: '让每个结论，回到证据。' }).waitFor();
await page.waitForFunction(() => document.querySelector('canvas')?.width > 200 && !document.querySelector('.reader-state'));
await page.screenshot({ path: 'artifacts/browser/01-workbench.png', fullPage: true });
await page.getByRole('button', { name: '训练用了哪些 GPU？', exact: true }).click();
await page.locator('.evidence-card').first().waitFor({ timeout: 120000 });
const gpuCard = page.locator('.evidence-card').filter({ hasText: 'P100' }).first();
if (!await gpuCard.count()) throw new Error('GPU evidence missing in browser');
await gpuCard.locator('.evidence-content').click();
await page.locator('[data-testid="source-highlight"]').waitFor();
await page.waitForFunction(() => !document.querySelector('.reader-state'));
await page.screenshot({ path: 'artifacts/browser/02-evidence.png', fullPage: true });
await gpuCard.getByRole('button', { name: '存为笔记' }).click();
await page.getByRole('textbox', { name: '证据笔记内容' }).fill('验收样例：Transformer 训练硬件的原文证据');
await page.getByRole('button', { name: '保存证据', exact: true }).click();
await page.getByRole('status').waitFor();
await page.locator('.nav-list').getByRole('button', { name: '证据笔记' }).click();
await page.getByRole('heading', { name: '证据笔记', exact: true }).waitFor();
await page.getByRole('heading', { name: '验收样例：Transformer 训练硬件的原文证据' }).first().waitFor();
await page.screenshot({ path: 'artifacts/browser/03-notes.png', fullPage: true });
await page.locator('.nav-list').getByRole('button', { name: '版本复核', exact: true }).click();
await page.getByRole('button', { name: '检查证据变化', exact: true }).click();
await page.locator('.audit-card').first().waitFor();
await page.screenshot({ path: 'artifacts/browser/04-audit.png', fullPage: true });
const auditCount = await page.locator('.audit-card').count();
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('.nav-list').getByRole('button', { name: '文献阅读台' }).click();
await page.waitForFunction(() => !document.querySelector('.reader-state'));
await page.screenshot({ path: 'artifacts/browser/05-mobile.png', fullPage: true });
const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
const result = { passed: errors.length === 0 && !overflows, page_errors: errors, failed_requests: failedRequests, audit_cards: auditCount, mobile_horizontal_overflow: overflows, screenshots: 5 };
await writeFile('artifacts/browser/results.json', JSON.stringify(result, null, 2));
await browser.close();
console.log(JSON.stringify(result, null, 2));
if (!result.passed) process.exitCode = 1;

import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('C:/Users/34711/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const folder = 'artifacts/attack-v16';
const protocol = JSON.parse(await readFile('evaluation/proof_v16_old/protocol.json', 'utf8'));
const item = protocol.qa.find(c => c.id === 'whisper_segments');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, baseURL: 'http://127.0.0.1:8767' });
const report = { notice: 'Actual model/browser, isolated database; exposed case, not independent evaluation.', checks: [], errors: [], answers: [] };
page.on('pageerror', error => report.errors.push(String(error)));
try {
  await page.goto('/');
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  report.checks.push('First-visit tutorial shown and dismissible');
  await page.getByLabel('筛选文献').fill(item.files[0]);
  await page.locator('.document-item').first().click();
  const pending = page.waitForResponse(r => r.url().endsWith('/api/ask') && r.request().method() === 'POST', { timeout: 300000 });
  await page.getByLabel('研究问题').fill(item.question);
  await page.getByLabel('研究问题').press('Enter');
  const response = await pending;
  assert(response.ok());
  const answer = await response.json();
  report.answers.push({ id: item.id, answer });
  const text = answer.model_answer.map(c => c.text).join(' ');
  for (const pattern of item.required_patterns) assert(new RegExp(pattern, 'i').test(text), pattern + ': ' + text);
  assert.equal(answer.subquestions.length, 2);
  assert(!(answer.subquestions || []).some(p => p.reason?.includes('处理失败')));
  const conditional = answer.model_answer.find(c => /采样|抽样|概率/.test(c.text));
  assert(conditional && conditional.page === 2 && /sub-sampled probability/.test(conditional.support_span));
  report.checks.push('Enter submits compound question and retains sampling condition with page-2 support');
  const saved = await (await page.request.get('/api/artifacts/' + answer.artifact_id)).json();
  assert.deepEqual(saved.content.sections[0].claims, answer.model_answer);
  report.checks.push('Saved artifact retains exact response and source anchors');
  const exported = await page.request.get('/api/artifacts/' + answer.artifact_id + '/export?format=md');
  assert(exported.ok());
  const markdown = await exported.text();
  for (const claim of answer.model_answer) assert(markdown.includes(claim.text));
  await writeFile(`${folder}/whisper-export.md`, markdown);
  report.checks.push('Markdown export retains both answers and sampling condition');
  await page.getByText('更多工具与成果', { exact: true }).click();
  await page.getByRole('button', { name: '任务与成果', exact: true }).click();
  await page.getByRole('button').filter({ hasText: item.question }).first().click();
  const artifact = page.locator('.artifact-result');
  await artifact.locator('.grounded-claim').first().waitFor();
  const labels = await artifact.locator('.grounded-claim > small').allTextContents();
  assert(labels.some(s => s.includes('没有语音的片段是否完全排除')));
  assert(labels.every(s => !s.includes('前文（仅用于确定指代对象）')));
  report.checks.push('Reopened artifact displays original subquestions');
  const claim = artifact.locator('.grounded-claim').filter({ hasText: conditional.text }).first();
  await claim.locator('.claim-source summary').click();
  assert.equal(await claim.locator('.claim-source blockquote').innerText(), conditional.quote);
  await artifact.screenshot({ path: `${folder}/direct-evidence-desktop.png` });
  report.checks.push('Expandable source preserves full probability and VAD paragraph');
  await claim.getByRole('button', { name: /第\s*2\s*页原文/ }).click();
  assert.equal(await page.getByLabel('当前页码').inputValue(), '2');
  await page.getByText('正在呈现原文', { exact: true }).waitFor({ state: 'hidden', timeout: 30000 });
  report.checks.push('Conditional claim opens and renders original PDF page 2');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: `${folder}/direct-evidence-mobile.png` });
  report.checks.push('390px mobile viewport has no page-level overflow');
  assert.deepEqual(report.errors, []);
} catch (error) {
  report.failure = String(error);
  await page.screenshot({ path: `${folder}/browser-failure.png` });
  throw error;
} finally {
  await writeFile(`${folder}/browser.json`, JSON.stringify(report, null, 2));
  await browser.close();
  console.log(JSON.stringify({ checks: report.checks, failure: report.failure, errors: report.errors }));
}

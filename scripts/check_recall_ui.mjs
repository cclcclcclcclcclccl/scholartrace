import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)('C:/Users/34711/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const folder = 'artifacts/recall-20261020', base = 'http://127.0.0.1:8767';
const fixture = JSON.parse(await readFile(`${folder}/fixture.json`, 'utf8'));
const report = { checks: [], errors: [] };
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.on('pageerror', e => report.errors.push(String(e)));
  await page.goto(base); await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /^证据笔记/ }).click();
  await page.getByRole('button', { name: '开始证据复习' }).click();
  const panel = page.getByRole('region', { name: '证据复习卡' });
  await panel.getByLabel('复习卡来源笔记').selectOption(String(fixture.note.id));
  const question = '评估使用多少个样本？请与对照组区分。';
  await panel.getByLabel('复习卡问题').fill(question);
  await panel.getByRole('button', { name: '创建并开始回忆' }).click();
  await panel.locator('.recall-card h3').getByText(question, { exact: true }).waitFor();
  assert.equal(await panel.locator('blockquote').count(), 0);
  assert.equal(await panel.getByRole('button', { name: /记得清楚/ }).count(), 0);
  await panel.getByLabel('我的回忆草稿').fill('我记得评估是73个样本，对照组不是这个数字。');
  await panel.screenshot({ path: `${folder}/desktop-question.png` });
  await panel.getByRole('button', { name: '揭示证据，核对回忆' }).click();
  assert.equal((await panel.locator('blockquote').textContent()).trim(), fixture.note.quote.trim());
  await panel.getByText('我记得评估是73个样本，对照组不是这个数字。', { exact: true }).waitFor();
  report.checks.push('Creates source-backed card; hides evidence and ratings until reveal; preserves private recall draft');
  await panel.getByRole('button', { name: '记得清楚 · 延后复习' }).click();
  await panel.getByText(/到期卡片已完成/).waitFor();
  let deck = await (await page.request.get(`${base}/api/recall`)).json();
  assert.equal(deck.cards.length, 1); assert.equal(deck.review_count, 1); assert.equal(deck.due_count, 0);
  assert.ok(!JSON.stringify(deck).includes('我记得评估'));
  report.checks.push('Self-rating persists once, schedules next review, and does not upload the recall draft');
  await page.reload();
  await page.getByRole('button', { name: /^证据笔记/ }).click();
  await page.getByRole('button', { name: '开始证据复习' }).click();
  await panel.getByText(/到期卡片已完成/).waitFor();
  await panel.getByLabel('也练习未到期的卡片').check();
  await panel.getByRole('button', { name: '揭示证据，核对回忆' }).click();
  assert.equal((await panel.locator('blockquote').textContent()).trim(), fixture.note.quote.trim());
  report.checks.push('Reload restores saved card and review schedule; optional early practice works');
  const download = page.waitForEvent('download');
  await panel.getByRole('link', { name: '导出 Anki TSV' }).click();
  await (await download).saveAs(`${folder}/export.tsv`);
  const tsv = await readFile(`${folder}/export.tsv`, 'utf8');
  assert.ok(tsv.includes(fixture.note.block_id) && tsv.includes('73 samples'));
  assert.equal(tsv.trim().split('\n').at(-1).split('\t').length, 3);
  report.checks.push('Anki TSV downloads with question, original evidence, source locator and tag');
  await panel.getByText('复习卡怎么玩？', { exact: true }).click();
  await panel.getByText(/自评“再想一遍”安排10分钟后复习/).waitFor();
  await panel.screenshot({ path: `${folder}/desktop-evidence.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await panel.screenshot({ path: `${folder}/mobile.png` });
  report.checks.push('Tutorial explains self-assessment limits and export; 390px layout fits');
  await panel.getByRole('button', { name: '回到论文原文' }).click();
  await page.getByRole('spinbutton', { name: '当前页码' }).waitFor();
  assert.equal(await page.getByRole('spinbutton', { name: '当前页码' }).inputValue(), '1');
  await page.waitForFunction(() => document.querySelector('canvas')?.width > 0 && !document.body.innerText.includes('正在呈现原文'));
  report.checks.push('Card opens the original PDF at its source page');
  const result = await (await page.request.post(`${base}/api/search`, { data: { question: '73', document_ids: [fixture.document_id] } })).json();
  assert.equal(result.evidence.length, 1); assert.equal(result.evidence[0].id, fixture.note.block_id);
  const missing = await (await page.request.post(`${base}/api/search`, { data: { question: '99999', document_ids: [fixture.document_id] } })).json();
  assert.deepEqual(missing.evidence, []);
  report.checks.push('Live numeric search returns 73 source only, excludes 173/73.5, and returns empty for absent numbers');
  assert.deepEqual(report.errors, []);
  report.card_id = deck.cards[0].id;
} catch (error) { report.failure = String(error.stack || error); process.exitCode = 1; }
finally { await writeFile(`${folder}/browser.json`, JSON.stringify(report, null, 2)); await browser.close(); }

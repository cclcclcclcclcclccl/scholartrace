import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)('C:/Users/34711/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base='http://127.0.0.1:8765';
const folder='artifacts/quality-round8/browser';
await mkdir(folder,{recursive:true});
const starter=JSON.parse(await readFile('artifacts/project-workspace-2026-10-14/starter-project.json','utf8'));
const dataset=JSON.parse(await readFile('tests/acceptance_questions_v6.json','utf8'));
const question=dataset.cases[0].question;
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
const report={checks:[],errors:[],requests:[]};
page.on('pageerror',e=>report.errors.push(String(e)));
page.on('request',r=>{if(r.url().endsWith('/api/ask')&&r.method()==='POST')report.requests.push(r.postDataJSON());});
try{
  await page.goto(`${base}/#project=${starter.id}`);
  await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'使用项目文献提问',exact:true}).click();
  const response=page.waitForResponse(r=>r.url().endsWith('/api/ask')&&r.request().method()==='POST',{timeout:180000});
  await page.getByLabel('研究问题',{exact:true}).fill(question);
  await page.getByLabel('研究问题',{exact:true}).press('Enter');
  console.log('真实多篇复合问答执行中');
  const http=await response;assert.equal(http.status(),200);
  const answer=await http.json();
  await writeFile(`${folder}/answer.json`,JSON.stringify(answer,null,2));
  assert.equal(answer.comparison.length,2);
  for(const row of answer.comparison){
    assert.equal(row.subquestions.length,2);
    assert.equal(row.subquestions[0].status,'reviewed_answer');
    assert.equal(row.subquestions[1].status,'unresolved');
    assert.ok(row.claims.some(c=>c.text.includes('P100')));
  }
  const cards=page.locator('.paper-answer');await cards.first().waitFor();assert.equal(await cards.count(),2);
  assert.equal(await cards.first().locator('.answer-coverage li').count(),2);
  await page.screenshot({path:`${folder}/multi-answer-desktop.png`});
  await page.setViewportSize({width:390,height:844});
  await cards.first().scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  for(const card of await cards.all())assert.equal(await card.evaluate(e=>e.scrollWidth<=e.clientWidth+1),true);
  await cards.first().screenshot({path:`${folder}/multi-answer-mobile-card.png`});
  report.checks.push('真实两篇问答各保留GPU答案和未知单次测量状态；手机卡片无横向溢出');
  await page.setViewportSize({width:1440,height:1000});
  const target=answer.comparison[0];
  const original=page.locator(`.paper-answer[data-document-id="${target.document_id}"]`);
  const sourceButton=original.getByRole('button',{name:/查看候选原文/}).first();
  const label=await sourceButton.innerText();const expectedPage=Number(label.match(/第\s*(\d+)\s*页/)[1]);
  await sourceButton.click();
  assert.equal(Number(await page.getByRole('spinbutton',{name:'当前页码'}).inputValue()),expectedPage);
  // Read the other paper first; a follow-up must still use its originating row.
  await cards.nth(1).getByRole('button',{name:'核对本篇原文',exact:true}).first().click();
  await original.getByRole('button',{name:'单独追问此项',exact:true}).click();
  assert.equal(await page.getByLabel('研究问题',{exact:true}).inputValue(),target.subquestions[1].question);
  assert.equal(await page.locator('#ask-scope').inputValue(),'multiple');
  assert.equal(await page.locator('.scope-papers input:checked').count(),1);
  assert.equal(report.requests.length,1);
  assert.equal(await cards.count(),2);
  report.checks.push('候选原文定位正确；查看另一篇后追问仍绑定原论文，未自动发送且保留旧回答');
  await page.locator('.paper-stage[aria-busy="false"]').waitFor();
  await page.screenshot({path:`${folder}/followup-prepared.png`});
  const followupResponse=page.waitForResponse(r=>r.url().endsWith('/api/ask')&&r.request().method()==='POST',{timeout:120000});
  await page.getByLabel('研究问题',{exact:true}).fill('模型训练用了哪些 GPU？');
  await page.getByLabel('研究问题',{exact:true}).press('Enter');
  const followup=await (await followupResponse).json();
  assert.deepEqual(report.requests[1].document_ids,[target.document_id]);
  assert.equal(report.requests[1].project_id,starter.id);
  assert.ok(followup.model_answer.some(c=>c.text.includes('P100')));
  const saved=await (await page.request.get(`${base}/api/artifacts/${answer.artifact_id}`)).json();
  assert.deepEqual(saved.content.sections[0].subquestions,answer.subquestions);
  const exported=await page.request.get(`${base}/api/artifacts/${answer.artifact_id}/export?format=md`);
  const markdown=await exported.text();
  assert.ok(markdown.includes('1706.03762v1.pdf')&&markdown.includes('1706.03762v7.pdf'));
  for(const row of answer.comparison)assert.ok(markdown.includes(row.subquestions[1].question));
  await writeFile(`${folder}/multi-answer-export.md`,markdown);
  await page.getByRole('button',{name:'返回项目',exact:true}).click();
  await page.getByRole('button',{name:/^研究成果 /}).click();
  const outputs=page.locator('.project-output').filter({hasText:question});
  await outputs.first().getByRole('button',{name:'打开成果',exact:true}).click();
  await page.locator('.artifact-result .answer-coverage').waitFor();
  assert.equal(await page.locator('.artifact-result .answer-coverage li').count(),4);
  await page.locator('.artifact-result').screenshot({path:`${folder}/saved-multi-answer.png`});
  report.artifacts=[answer.artifact_id,followup.artifact_id];
  report.checks.push('编辑后Enter提交只查询原论文并保留项目；原复合回答可重开，导出能区分同名论文版本');
  assert.deepEqual(report.errors,[]);report.passed=true;
}catch(e){report.failure=String(e);await page.screenshot({path:`${folder}/failure.png`,fullPage:true});throw e;}
finally{await writeFile(`${folder}/report.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));await browser.close();}
